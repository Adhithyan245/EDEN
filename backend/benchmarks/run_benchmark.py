"""EDEN benchmark runner (eden-bench-v1).

Drives EDEN's real message entry point, ``app.main._handle_user_message``,
with a fake WebSocket, so every request goes through the production path:
intent detection -> router -> clarification -> orchestrator / edit
orchestrator -> planner -> static validator -> file writes -> npm install.

On top of EDEN's own success signal (a ``build_complete`` / ``edit_complete``
event), the harness runs an independent check that EDEN itself does not:
``npm run build`` (vite build) in the generated workspace. A task only counts
as passing end to end when both succeed. vite build proves the code compiles
and its imports resolve. It does not prove the UI renders or behaves correctly.

Differences from a live session, by design:
  - EDEN_VOICE_ENABLED=false: browser TTS instead of ElevenLabs (no TTS spend).
    Narration text is still generated by the LLM, so LLM calls are unaffected.
  - EDEN_MEMORY_ENABLED=false: the build/edit path never touches memory, and
    this keeps a misrouted request from writing to the real memory store.
  - EDEN_PORT is set to an unused port, because importing app.main force-kills
    any other process listening on EDEN_PORT.

Usage (from backend/):
    ../.venv/Scripts/python.exe benchmarks/run_benchmark.py [--only B01,B02] [--pause 12]
"""

from __future__ import annotations

import argparse
import asyncio
import inspect
import json
import logging
import os
import subprocess
import sys
import time
from datetime import datetime
from pathlib import Path

HERE = Path(__file__).resolve().parent
BACKEND = HERE.parent

os.environ["EDEN_PORT"] = "65011"
os.environ["EDEN_VOICE_ENABLED"] = "false"
os.environ["EDEN_MEMORY_ENABLED"] = "false"
os.environ["EDEN_AGENT_ENABLED"] = "true"
sys.path.insert(0, str(BACKEND))

import app.main as M  # noqa: E402  (env must be set first)
from app.session import Session  # noqa: E402


# ---------------------------------------------------------------------------
# Instrumentation
# ---------------------------------------------------------------------------

class Meter:
    """Per-turn counters for LLM calls, tokens and log-derived signals."""

    def __init__(self) -> None:
        self.reset()

    def reset(self) -> None:
        self.calls: list[dict] = []
        self.logs: list[str] = []


METER = Meter()


def _caller_phase() -> str:
    for fr in inspect.stack()[2:]:
        mod = fr.frame.f_globals.get("__name__", "")
        if mod.startswith("app.") and not mod.startswith("app.providers"):
            return mod.removeprefix("app.")
    return "unknown"


def _instrument_llm() -> None:
    models = M.LLM._client.aio.models
    original = models.generate_content_stream

    async def wrapped(**kwargs):
        rec = {"phase": _caller_phase(), "model": kwargs.get("model"),
               "prompt_tokens": 0, "output_tokens": 0, "total_tokens": 0, "error": None}
        METER.calls.append(rec)
        try:
            stream = await original(**kwargs)
        except Exception as exc:  # noqa: BLE001
            rec["error"] = f"{type(exc).__name__}: {str(exc)[:200]}"
            raise

        async def gen():
            try:
                async for chunk in stream:
                    um = getattr(chunk, "usage_metadata", None)
                    if um is not None:
                        rec["prompt_tokens"] = max(rec["prompt_tokens"], um.prompt_token_count or 0)
                        rec["output_tokens"] = max(rec["output_tokens"], um.candidates_token_count or 0)
                        rec["total_tokens"] = max(rec["total_tokens"], um.total_token_count or 0)
                    yield chunk
            except Exception as exc:  # noqa: BLE001
                rec["error"] = f"{type(exc).__name__}: {str(exc)[:200]}"
                raise

        return gen()

    models.generate_content_stream = wrapped


class _Capture(logging.Handler):
    def emit(self, record: logging.LogRecord) -> None:
        METER.logs.append(f"{record.name}: {record.getMessage()}")


class FakeWS:
    def __init__(self) -> None:
        self.events: list[dict] = []

    async def send_json(self, data: dict) -> None:
        self.events.append(data)

    async def send_bytes(self, data: bytes) -> None:
        self.events.append({"type": "_audio_bytes", "n": len(data)})

    async def send_text(self, data: str) -> None:
        self.events.append({"type": "_text", "n": len(data)})


# ---------------------------------------------------------------------------
# Checks
# ---------------------------------------------------------------------------

def vite_build(workspace: str) -> tuple[bool, float, str]:
    t0 = time.perf_counter()
    try:
        r = subprocess.run("npm run build", cwd=workspace, shell=True, capture_output=True,
                           text=True, encoding="utf-8", errors="replace", timeout=180)
        ok = r.returncode == 0
        tail = (r.stdout + r.stderr)[-600:]
    except Exception as exc:  # noqa: BLE001
        ok, tail = False, str(exc)
    return ok, round(time.perf_counter() - t0, 1), tail


async def run_turn(ws: FakeWS, session: Session, text: str) -> dict:
    METER.reset()
    start = len(ws.events)
    t0 = time.perf_counter()
    error = None
    try:
        await M._handle_user_message(ws, session, text)
    except Exception as exc:  # noqa: BLE001
        error = f"{type(exc).__name__}: {exc}"
    secs = round(time.perf_counter() - t0, 1)
    evs = ws.events[start:]
    types = [e.get("type") for e in evs]
    routing = next((e for e in evs if e.get("type") == "agent_routing"), None)
    return {
        "text": text,
        "seconds": secs,
        "error": error,
        "event_types": sorted(set(t for t in types if t)),
        "route": routing.get("route") if routing else None,
        "intent": routing.get("intent") if routing else None,
        "build_complete": next((e for e in evs if e.get("type") == "build_complete"), None),
        "build_failed": next((e for e in evs if e.get("type") == "build_failed"), None),
        "edit_complete": next((e for e in evs if e.get("type") == "edit_complete"), None),
        "edit_failed": next((e for e in evs if e.get("type") == "edit_failed"), None),
        "clarification": next((e.get("question") for e in evs
                               if e.get("type") == "clarification_requested"), None),
        "llm_calls": list(METER.calls),
        "repair_attempted": any(("attempting one repair" in l) or ("build generation rejected" in l)
                                for l in METER.logs),
        "rejections": [l for l in METER.logs
                       if "build generation rejected" in l or "edit failed validation" in l],
        "transient_retries": sum("— retrying" in l for l in METER.logs),
        "fallback_served": sum("served by fallback model" in l for l in METER.logs),
        "validation_logs": [l for l in METER.logs
                            if "validation" in l.lower() or "invalid" in l.lower()
                            or "no usable App" in l],
        "llm_errors": [c["error"] for c in METER.calls if c["error"]],
    }


def _merge(a: dict, b: dict) -> dict:
    """Combine a clarification turn with the follow-up build turn."""
    out = dict(b)
    out["seconds"] = round(a["seconds"] + b["seconds"], 1)
    out["llm_calls"] = a["llm_calls"] + b["llm_calls"]
    out["llm_errors"] = a["llm_errors"] + b["llm_errors"]
    out["clarification"] = a["clarification"]
    out["route"], out["intent"] = a["route"], a["intent"]
    out["validation_logs"] = a["validation_logs"] + b["validation_logs"]
    out["transient_retries"] = a["transient_retries"] + b["transient_retries"]
    out["fallback_served"] = a["fallback_served"] + b["fallback_served"]
    return out


async def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", default="")
    ap.add_argument("--pause", type=float, default=12.0,
                    help="seconds between turns, to stay under free-tier rate limits")
    ap.add_argument("--out", default=str(HERE / "results"))
    args = ap.parse_args()

    spec = json.loads((HERE / "tasks.json").read_text(encoding="utf-8"))
    only = {s.strip() for s in args.only.split(",") if s.strip()}
    tasks = [t for t in spec["tasks"] if not only or t["id"] in only]

    logging.getLogger("eden").addHandler(_Capture())
    _instrument_llm()
    print(f"LLM={M.LLM.name} TTS={M.TTS.name} model_voice={M.settings.model_voice} "
          f"model_builder={M.settings.model_builder} tasks={len(tasks)}", flush=True)

    results = []
    for t in tasks:
        ws, session = FakeWS(), Session()
        rec: dict = {"id": t["id"]}

        b = await run_turn(ws, session, t["build"])
        if b["clarification"] and session.pending_clarification is not None:
            await asyncio.sleep(args.pause)
            b = _merge(b, await run_turn(ws, session, spec["clarification_answer"]))
        rec["build"] = b
        ws_path = (b["build_complete"] or {}).get("workspace")
        if ws_path:
            ok, secs, tail = vite_build(ws_path)
            b["vite_build_ok"], b["vite_build_seconds"], b["vite_tail"] = ok, secs, tail
        else:
            b["vite_build_ok"] = False
        b["pass"] = bool(b["build_complete"]) and b["vite_build_ok"]
        b["infra_error"] = any(("503" in x or "429" in x or "UNAVAILABLE" in x
                                or "RESOURCE_EXHAUSTED" in x) for x in b["llm_errors"])
        print(f"{t['id']} build: complete={bool(b['build_complete'])} vite={b['vite_build_ok']} "
              f"route={b['route']} clar={bool(b['clarification'])} {b['seconds']}s "
              f"calls={len(b['llm_calls'])} err={b['error'] or b['llm_errors'][:1]}", flush=True)

        if t.get("edit") and b["build_complete"]:
            await asyncio.sleep(args.pause)
            e = await run_turn(ws, session, t["edit"])
            if e["edit_complete"]:
                ok, secs, tail = vite_build(ws_path)
                e["vite_build_ok"], e["vite_build_seconds"], e["vite_tail"] = ok, secs, tail
            else:
                e["vite_build_ok"] = False
            e["pass"] = bool(e["edit_complete"]) and e["vite_build_ok"]
            e["infra_error"] = any(("503" in x or "429" in x or "UNAVAILABLE" in x
                                    or "RESOURCE_EXHAUSTED" in x) for x in e["llm_errors"])
            rec["edit"] = e
            print(f"{t['id']} edit: complete={bool(e['edit_complete'])} vite={e['vite_build_ok']} "
                  f"route={e['route']} repair={e['repair_attempted']} {e['seconds']}s "
                  f"calls={len(e['llm_calls'])} err={e['error'] or e['llm_errors'][:1]}", flush=True)
        elif t.get("edit"):
            rec["edit"] = {"skipped": "build did not complete"}

        results.append(rec)
        await asyncio.sleep(args.pause)

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    path = out / f"run-{stamp}.json"
    path.write_text(json.dumps({
        "benchmark": spec["name"], "run_at": stamp,
        "llm": M.LLM.name, "model_voice": M.settings.model_voice,
        "model_builder": M.settings.model_builder, "results": results,
    }, indent=2, default=str), encoding="utf-8")
    print(f"wrote {path}", flush=True)


if __name__ == "__main__":
    asyncio.run(main())
